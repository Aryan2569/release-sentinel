"""Generate hash-locked requirements-action.lock for GitHub Action execution.

Includes cryptographic hashes for Linux x86_64 and Windows x86_64 across Python 3.12 and 3.14.
"""

from __future__ import annotations

import httpx

PACKAGES = {
    "annotated-types": "0.7.0",
    "anyio": "4.8.0",
    "certifi": "2024.12.14",
    "click": "8.1.8",
    "colorama": "0.4.6",
    "h11": "0.16.0",
    "httpcore": "1.0.9",
    "httpx": "0.28.1",
    "idna": "3.10",
    "markdown-it-py": "3.0.0",
    "mdurl": "0.1.2",
    "node-semver": "0.9.1",
    "pydantic": "2.14.1",
    "pydantic-core": "2.50.1",
    "pygments": "2.19.1",
    "rich": "13.9.4",
    "shellingham": "1.5.4",
    "sniffio": "1.3.1",
    "typer": "0.15.1",
    "typing-extensions": "4.16.0",
    "typing-inspection": "0.4.4",
}


def main() -> None:
    lines = [
        "#",
        "# This file is autogenerated by release-sentinel for GitHub Action.",
        "# Includes hashes for Linux x86_64 and Windows x86_64, Python 3.12 and 3.14.",
        "# To update, run: python scripts/generate_action_lock.py",
        "#",
    ]

    with httpx.Client(timeout=60.0) as client:
        for name, ver in sorted(PACKAGES.items()):
            url = f"https://pypi.org/pypi/{name}/{ver}/json"
            resp = client.get(url)
            resp.raise_for_status()
            data = resp.json()
            urls = data.get("urls", [])
            hashes = sorted(
                {u["digests"]["sha256"] for u in urls if "sha256" in u.get("digests", {})}
            )

            pkg_header = f"{name}=={ver} \\"
            lines.append(pkg_header)
            for i, h in enumerate(hashes):
                continuation = " \\" if i < len(hashes) - 1 else ""
                lines.append(f"    --hash=sha256:{h}{continuation}")

    content = "\n".join(lines) + "\n"
    with open("requirements-action.lock", "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(
        "Successfully generated requirements-action.lock with Linux and Windows hashes "
        "for Python 3.12 and 3.14."
    )


if __name__ == "__main__":
    main()
