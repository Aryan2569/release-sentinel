"""Generate hash-locked requirements-action.lock for GitHub Action execution."""

from __future__ import annotations

import httpx

PACKAGES = {
    "annotated-types": "0.7.0",
    "anyio": "4.8.0",
    "certifi": "2024.12.14",
    "click": "8.1.8",
    "h11": "0.14.0",
    "httpcore": "1.0.7",
    "httpx": "0.28.1",
    "idna": "3.10",
    "markdown-it-py": "3.0.0",
    "mdurl": "0.1.2",
    "node-semver": "0.9.1",
    "pydantic": "2.10.6",
    "pydantic-core": "2.27.2",
    "pygments": "2.19.1",
    "rich": "13.9.4",
    "shellingham": "1.5.4",
    "sniffio": "1.3.1",
    "typer": "0.15.1",
    "typing-extensions": "4.12.2",
}


def main() -> None:
    lines = [
        "#",
        "# This file is autogenerated by release-sentinel for GitHub Action (Python 3.12)",
        "# To update, run: python scripts/generate_action_lock.py",
        "#",
    ]

    for name, ver in sorted(PACKAGES.items()):
        url = f"https://pypi.org/pypi/{name}/{ver}/json"
        resp = httpx.get(url, timeout=30.0)
        resp.raise_for_status()
        data = resp.json()
        urls = data.get("urls", [])
        hashes = sorted({u["digests"]["sha256"] for u in urls if "sha256" in u.get("digests", {})})

        pkg_header = f"{name}=={ver} \\"
        lines.append(pkg_header)
        for i, h in enumerate(hashes):
            continuation = " \\" if i < len(hashes) - 1 else ""
            lines.append(f"    --hash=sha256:{h}{continuation}")

    content = "\n".join(lines) + "\n"
    with open("requirements-action.lock", "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print("Successfully generated requirements-action.lock")


if __name__ == "__main__":
    main()
